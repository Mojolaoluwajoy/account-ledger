-- Outbox of ledger entries waiting to be sent to the ledger service.
-- "if not exists" because databases that ran the service under ddl-auto=update
-- before Flyway was introduced may already have this table.

create table if not exists ledger_postings (
    id                    bigint generated by default as identity primary key,
    transaction_type      varchar(255) not null,
    amount                numeric(38, 2) not null,
    transaction_reference varchar(255) not null,
    description           varchar(255),
    status                varchar(255) not null,
    attempts              integer not null,
    last_error            varchar(255),
    created_at            timestamp(6) not null,
    posted_at             timestamp(6),
    constraint uk_ledger_postings_transaction_reference unique (transaction_reference),
    constraint ledger_postings_status_check check (status in ('PENDING', 'POSTED'))
);

-- The publisher polls for PENDING rows every few seconds.
create index if not exists idx_ledger_postings_status on ledger_postings (status, id);
