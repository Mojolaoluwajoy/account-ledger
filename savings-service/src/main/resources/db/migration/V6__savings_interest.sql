-- Interest earned by each account, one row per account per day. Rows are
-- added up and paid into the account once a month; posting_reference is set
-- once a row has been paid.
create table interest_accruals (
    id                bigint generated by default as identity primary key,
    account_id        bigint not null,
    accrual_date      date not null,
    balance           numeric(38, 2) not null,
    annual_rate       numeric(38, 2) not null,
    amount            numeric(38, 6) not null,
    posting_reference varchar(255),
    created_at        timestamp(6) not null,
    constraint fk_interest_accruals_account foreign key (account_id) references savings_accounts (id),
    -- One accrual per account per day, so running the job twice changes nothing.
    constraint uk_interest_accruals_account_date unique (account_id, accrual_date)
);

-- The monthly posting looks up each account's rows that are not paid yet.
create index idx_interest_accruals_unposted on interest_accruals (account_id, posting_reference);

alter table savings_transactions
    drop constraint if exists savings_transactions_transaction_type_check;
alter table savings_transactions
    add constraint savings_transactions_transaction_type_check
        check (transaction_type in ('WITHDRAWAL', 'DEPOSIT', 'TRANSFER_OUT', 'TRANSFER_IN',
                                    'FIXED_DEPOSIT_PAYOUT', 'INTEREST'));
