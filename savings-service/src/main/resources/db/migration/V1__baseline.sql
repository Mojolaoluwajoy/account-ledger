-- Schema as it stood when Flyway was introduced.
-- Databases that already have these tables are baselined at version 1 and skip this file.

create table savings_products (
    id                           bigint generated by default as identity primary key,
    name                         varchar(255) not null,
    short_name                   varchar(255) not null,
    description                  varchar(255),
    nominal_annual_interest_rate numeric(38, 2) not null,
    minimum_opening_balance      numeric(38, 2) not null,
    minimum_balance              numeric(38, 2) not null,
    enforce_minimum_balance      boolean not null,
    created_at                   timestamp(6) not null,
    constraint uk_savings_products_short_name unique (short_name)
);

create table savings_accounts (
    id                bigint generated by default as identity primary key,
    client_id         bigint not null,
    product_id        bigint not null,
    account_number    varchar(255) not null,
    balance           numeric(38, 2) not null,
    available_balance numeric(38, 2) not null,
    status            varchar(255) not null,
    created_at        timestamp(6) not null,
    constraint uk_savings_accounts_account_number unique (account_number),
    constraint fk_savings_accounts_product foreign key (product_id) references savings_products (id),
    constraint savings_accounts_status_check
        check (status in ('PENDING', 'ACTIVE', 'DORMANT', 'CLOSED'))
);

create table savings_transactions (
    id               bigint generated by default as identity primary key,
    account_id       bigint not null,
    transaction_type varchar(255) not null,
    amount           numeric(38, 2) not null,
    balance_before   numeric(38, 2) not null,
    balance_after    numeric(38, 2) not null,
    description      varchar(255),
    transaction_date timestamp(6) not null,
    constraint fk_savings_transactions_account foreign key (account_id) references savings_accounts (id),
    constraint savings_transactions_transaction_type_check
        check (transaction_type in ('WITHDRAWAL', 'DEPOSIT'))
);
