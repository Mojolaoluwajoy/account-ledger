-- Schema as it stood when Flyway was introduced.
-- Databases that already have these tables are baselined at version 1 and skip this file.

create table clients (
    id                 bigint generated by default as identity primary key,
    fineract_client_id bigint,
    first_name         varchar(255) not null,
    last_name          varchar(255) not null,
    email              varchar(255) not null,
    phone_number       varchar(255) not null,
    date_of_birth      date,
    status             varchar(255) not null,
    created_at         timestamp(6) not null,
    constraint uk_clients_email unique (email),
    constraint clients_status_check check (status in ('PENDING', 'ACTIVE', 'INACTIVE'))
);
