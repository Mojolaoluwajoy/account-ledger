-- Schema as it stood when Flyway was introduced.
-- Databases that already have these tables are baselined at version 1 and skip this file.

create table fixed_deposits (
    id               bigint generated by default as identity primary key,
    client_id        bigint not null,
    principal_amount numeric(38, 2) not null,
    interest_rate    numeric(38, 2) not null,
    tenure_in_days   integer not null,
    deposit_date     date not null,
    maturity_date    date not null,
    maturity_amount  numeric(38, 2) not null,
    status           varchar(255) not null,
    created_at       timestamp(6) not null,
    constraint fixed_deposits_status_check check (status in ('ACTIVE', 'MATURED', 'CLOSED'))
);
