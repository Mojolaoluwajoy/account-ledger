-- Schema as it stood when Flyway was introduced.
-- Databases that already have these tables are baselined at version 1 and skip this file.

create table gl_accounts (
    id           bigint generated by default as identity primary key,
    account_code varchar(255) not null,
    account_name varchar(255) not null,
    account_type varchar(255) not null,
    description  varchar(255),
    created_at   timestamp(6) not null,
    constraint uk_gl_accounts_account_code unique (account_code),
    constraint gl_accounts_account_type_check
        check (account_type in ('ASSET', 'LIABILITY', 'INCOME', 'EXPENSE'))
);

create table ledger_entries (
    id                    bigint generated by default as identity primary key,
    transaction_reference varchar(255),
    transaction_type      varchar(255) not null,
    debit_account_id      bigint not null,
    credit_account_id     bigint not null,
    amount                numeric(38, 2) not null,
    description           varchar(255),
    entry_date            timestamp(6) not null,
    constraint fk_ledger_entries_debit_account foreign key (debit_account_id) references gl_accounts (id),
    constraint fk_ledger_entries_credit_account foreign key (credit_account_id) references gl_accounts (id),
    constraint ledger_entries_transaction_type_check
        check (transaction_type in ('SAVINGS_DEPOSIT', 'SAVINGS_WITHDRAWAL',
                                    'FIXED_DEPOSIT_CREATION', 'FIXED_DEPOSIT_MATURITY'))
);
